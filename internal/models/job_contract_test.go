func TestCanonicalErrorCodeFallbackIsConservative(t *testing.T) {
	tests := []struct {
		name       string
		detailCode string
		want       string
	}{
		{name: "empty", detailCode: "", want: ErrorCodeUnclassified},
		{name: "whitespace", detailCode: "   ", want: ErrorCodeUnclassified},
		{name: "unknown domain code", detailCode: "IMAGE_FUTURE_FAILURE", want: ErrorCodeUnclassified},
		{name: "unknown unrelated code", detailCode: "FAKE_EXECUTION_FAILED", want: ErrorCodeUnclassified},
		{name: "submit error", detailCode: "SUBMIT_ERROR", want: ErrorCodeUnclassified},
		{name: "interrupted lifecycle", detailCode: "JOB_INTERRUPTED", want: ErrorCodeUnclassified},
		{name: "plan mismatch", detailCode: "PLAN_EXECUTION_MISMATCH", want: ErrorCodeUnclassified},
		{name: "timeout", detailCode: "JOB_TIMEOUT", want: ErrorCodeExecTimeoutTransient},
		{name: "lifecycle cancelled", detailCode: "JOB_CANCELLED", want: ErrorCodeCancelledByUser},
		{name: "canceled spelling", detailCode: "CANCELED", want: ErrorCodeCancelledByUser},
		{name: "validation keyword", detailCode: "VALIDATION_ERROR", want: ErrorCodeValidationInvalidInput},
		{name: "not found keyword", detailCode: "TOOL_NOT_FOUND", want: ErrorCodeValidationInvalidInput},
		{name: "plan missing keyword", detailCode: "PLAN_MISSING", want: ErrorCodeValidationInvalidInput},
		{name: "unsupported keyword", detailCode: "PLAN_UNSUPPORTED", want: ErrorCodeUnsupportedFormat},
		{name: "runtime keyword", detailCode: "SOME_RUNTIME_PROBLEM", want: ErrorCodeRuntimeDepMissing},
		{name: "dependency keyword", detailCode: "SOME_DEPENDENCY_PROBLEM", want: ErrorCodeRuntimeDepMissing},
		{name: "dep missing keyword", detailCode: "SOME_DEP_MISSING", want: ErrorCodeRuntimeDepMissing},
		{name: "execution failure system code", detailCode: "EXECUTION_FAILED", want: ErrorCodeExecIOTransient},
		{name: "panic system code", detailCode: "PANIC", want: ErrorCodeExecIOTransient},
		{name: "lowercase input", detailCode: " image_compress_execution ", want: ErrorCodeExecIOTransient},
	}

	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			if got := CanonicalErrorCode(tt.detailCode); got != tt.want {
				t.Fatalf("CanonicalErrorCode(%q) = %q, want %q", tt.detailCode, got, tt.want)
			}
		})
	}
}

func TestNewCanonicalJobErrorUsesClassifiedCode(t *testing.T) {
	jobErr := NewCanonicalJobError("IMAGE_COMPRESS_BATCH_ITEM", "compression failed", nil)
	if jobErr.Code != ErrorCodeExecIOTransient {
		t.Fatalf("code = %q, want %q", jobErr.Code, ErrorCodeExecIOTransient)
	}
	if jobErr.DetailCode != "IMAGE_COMPRESS_BATCH_ITEM" {
		t.Fatalf("detail code = %q, want the original code", jobErr.DetailCode)
	}

	unknown := NewCanonicalJobError("FUTURE_UNKNOWN_FAILURE", "unknown", nil)
	if unknown.Code != ErrorCodeUnclassified {
		t.Fatalf("unknown code = %q, want %q", unknown.Code, ErrorCodeUnclassified)
	}
}
