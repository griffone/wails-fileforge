func assertCanonicalCodes(t *testing.T, cases map[string]string) {
	t.Helper()

	for detailCode, want := range cases {
		if got := CanonicalErrorCode(detailCode); got != want {
			t.Errorf("CanonicalErrorCode(%q) = %q, want %q", detailCode, got, want)
		}
	}
}

