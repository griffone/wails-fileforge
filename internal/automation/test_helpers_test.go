const (
	testRecipeID   = "recipe.test"
	testRecipeName = "Test recipe"
)

// fakeRecipeRunner is a controllable RecipeRunner for watcher/service tests.
type fakeRecipeRunner struct {
	mu sync.Mutex

	recipes []models.RecipeV1

	runs       []models.RecipeRequestV1
	runCh      chan models.RecipeRequestV1
	jobCounter int
	jobs       map[string]*fakeRecipeJob

	failPlan    bool
	planMessage string
	planOutput  func(req models.RecipeRequestV1) string

	failRun    bool
	runMessage string

	writeOutput         bool
	terminalStatus      string
	terminalMessage     string
	pollsBeforeTerminal int
	missingStatus       bool
	statusCalls         int
}

type fakeRecipeJob struct {
	recipeID string
	output   string
	polls    int
}

func newFakeRecipeRunner() *fakeRecipeRunner {
	return &fakeRecipeRunner{
		recipes: []models.RecipeV1{{
			ID:               testRecipeID,
			Name:             testRecipeName,
			Description:      "Converts text files for automation tests.",
			Category:         "test",
			InputKind:        "text",
			AcceptExtensions: []string{"txt"},
			Steps: []models.RecipeStepV1{{
				ID:     "convert",
				Name:   "Convert text",
				ToolID: "tool.test",
			}},
		}},
		runCh:          make(chan models.RecipeRequestV1, 32),
		jobs:           make(map[string]*fakeRecipeJob),
		writeOutput:    true,
		terminalStatus: models.JobStatusSuccess,
	}
}

func (f *fakeRecipeRunner) List() []models.RecipeV1 {
	f.mu.Lock()
	defer f.mu.Unlock()

	recipes := make([]models.RecipeV1, len(f.recipes))
	copy(recipes, f.recipes)

	return recipes
}

func (f *fakeRecipeRunner) Plan(req models.RecipeRequestV1) models.RecipePlanResponseV1 {
	f.mu.Lock()
	fail := f.failPlan
	message := f.planMessage
	output := f.plannedOutputLocked(req)
	f.mu.Unlock()

	if fail {
		if message == "" {
			message = "The test recipe could not plan this file."
		}

		return models.RecipePlanResponseV1{Success: false, Message: message}
	}

	recipe := f.recipeByID(req.RecipeID)

	return models.RecipePlanResponseV1{
		Success:    true,
		Message:    "The test recipe is ready.",
		Recipe:     recipe,
		InputPaths: req.InputPaths,
		OutputDir:  req.OutputDir,
		Outputs: []models.PlannedOutputV1{{
			InputPath:   firstPath(req.InputPaths),
			OutputPath:  output,
			OutputKind:  "file",
			OutputCount: 1,
		}},
	}
}

func (f *fakeRecipeRunner) Run(_ context.Context, req models.RecipeRequestV1) models.RunRecipeResponseV1 {
	f.mu.Lock()
	f.runs = append(f.runs, req)
	f.jobCounter++
	jobID := fmt.Sprintf("job_%d", f.jobCounter)
	output := f.plannedOutputLocked(req)
	f.jobs[jobID] = &fakeRecipeJob{recipeID: req.RecipeID, output: output}
	failRun := f.failRun
	runMessage := f.runMessage
	writeOutput := f.writeOutput
	f.mu.Unlock()

	if failRun {
		if runMessage == "" {
			runMessage = "The test recipe could not be started."
		}

		return models.RunRecipeResponseV1{
			Success: false,
			Message: runMessage,
			Status:  models.JobStatusFailed,
		}
	}

	if writeOutput {
		_ = os.MkdirAll(filepath.Dir(output), 0o755)
		_ = os.WriteFile(output, []byte("generated by the test recipe"), 0o644)
	}

	select {
	case f.runCh <- req:
	default:
	}

	return models.RunRecipeResponseV1{
		Success: true,
		Message: "recipe submitted",
		JobID:   jobID,
		Status:  models.JobStatusQueued,
	}
}

func (f *fakeRecipeRunner) Status(jobID string) models.RecipeStatusResponseV1 {
	f.mu.Lock()
	defer f.mu.Unlock()

	job, found := f.jobs[jobID]
	if !found || f.missingStatus {
		return models.RecipeStatusResponseV1{
			Success: false,
			Found:   false,
			Message: "recipe job not found",
		}
	}

	f.statusCalls++
	job.polls++
	if job.polls <= f.pollsBeforeTerminal {
		return models.RecipeStatusResponseV1{
			Success: true,
			Found:   true,
			Message: "recipe status retrieved",
			Result: &models.RecipeResultV1{
				JobID:     jobID,
				RecipeID:  job.recipeID,
				Status:    models.JobStatusRunning,
				Message:   "recipe running",
				Steps:     []models.RecipeStepResultV1{},
				Outputs:   []string{},
				StartedAt: 1,
			},
		}
	}

	status := f.terminalStatus
	if status == "" {
		status = models.JobStatusSuccess
	}
	message := f.terminalMessage
	if message == "" {
		switch status {
		case models.JobStatusFailed:
			message = "The test recipe failed."
		case models.JobStatusPartialSuccess:
			message = "The test recipe finished with issues."
		case models.JobStatusCancelled:
			message = "The test recipe was cancelled."
		default:
			message = "The test recipe finished."
		}
	}

	outputs := []string{}
	if status == models.JobStatusSuccess || status == models.JobStatusPartialSuccess {
		outputs = append(outputs, job.output)
	}

	return models.RecipeStatusResponseV1{
		Success: true,
		Found:   true,
		Message: "recipe status retrieved",
		Result: &models.RecipeResultV1{
			JobID:     jobID,
			RecipeID:  job.recipeID,
			Status:    status,
			Message:   message,
			Steps:     []models.RecipeStepResultV1{},
			Outputs:   outputs,
			StartedAt: 1,
			EndedAt:   2,
		},
	}
}

func (f *fakeRecipeRunner) plannedOutputLocked(req models.RecipeRequestV1) string {
	if f.planOutput != nil {
		return f.planOutput(req)
	}

	input := firstPath(req.InputPaths)
	base := strings.TrimSuffix(filepath.Base(input), filepath.Ext(input)) + "-out.txt"
	directory := strings.TrimSpace(req.OutputDir)
	if directory == "" {
		directory = filepath.Dir(input)
	}

	return filepath.Join(directory, base)
}

func (f *fakeRecipeRunner) recipeByID(id string) *models.RecipeV1 {
	f.mu.Lock()
	defer f.mu.Unlock()

	for index := range f.recipes {
		if f.recipes[index].ID == id {
			recipe := f.recipes[index]

			return &recipe
		}
	}

	return nil
}

func (f *fakeRecipeRunner) runCount() int {
	f.mu.Lock()
	defer f.mu.Unlock()

	return len(f.runs)
}

func (f *fakeRecipeRunner) statusCallCount() int {
	f.mu.Lock()
	defer f.mu.Unlock()

	return f.statusCalls
}

func (f *fakeRecipeRunner) runsSnapshot() []models.RecipeRequestV1 {
	f.mu.Lock()
	defer f.mu.Unlock()

	return append([]models.RecipeRequestV1(nil), f.runs...)
}

func firstPath(paths []string) string {
	if len(paths) == 0 {
		return ""
	}

	return paths[0]
}

func newTestService(t *testing.T, runner RecipeRunner, emit func(models.AutomationRunEventV1)) (*Service, *Store) {
	t.Helper()

	root := t.TempDir()
	store := NewStore(filepath.Join(root, "automation_rules_v1.json"))
	service := NewService(store, runner, emit)
	service.stabilityDelay = 30 * time.Millisecond
	service.statusPollInterval = 5 * time.Millisecond
	service.runTimeout = 2 * time.Second
	service.producedTTL = time.Minute

	return service, store
}

func startService(t *testing.T, service *Service) {
	t.Helper()

	service.Start(context.Background())
	t.Cleanup(service.Shutdown)
	// Give fsnotify inotify a moment to install the watch.
	time.Sleep(50 * time.Millisecond)
}

func saveTestRule(t *testing.T, service *Service, rule models.AutomationRuleV1) models.AutomationRuleV1 {
	t.Helper()

	response := service.SaveRule(rule)
	if !response.Success {
		t.Fatalf("SaveRule failed: %s (%+v)", response.Message, response.Error)
	}
	if response.Rule == nil {
		t.Fatal("SaveRule returned no rule")
	}

	return *response.Rule
}

func waitFor(t *testing.T, timeout time.Duration, what string, condition func() bool) {
	t.Helper()

	deadline := time.Now().Add(timeout)
	for time.Now().Before(deadline) {
		if condition() {
			return
		}
		time.Sleep(5 * time.Millisecond)
	}

	t.Fatalf("timed out waiting for %s", what)
}

func waitForRunCount(t *testing.T, runner *fakeRecipeRunner, want int, timeout time.Duration) {
	t.Helper()

	waitFor(t, timeout, fmt.Sprintf("%d recipe run(s)", want), func() bool {
		return runner.runCount() >= want
	})
	if got := runner.runCount(); got != want {
		t.Fatalf("expected exactly %d run(s), got %d", want, got)
	}
}

func assertNoRun(t *testing.T, runner *fakeRecipeRunner, wait time.Duration) {
	t.Helper()

	assertRunStaysAt(t, runner, 0, wait)
}

func assertRunStaysAt(t *testing.T, runner *fakeRecipeRunner, want int, wait time.Duration) {
	t.Helper()

	time.Sleep(wait)
	if got := runner.runCount(); got != want {
		t.Fatalf("expected %d recipe run(s) after waiting, got %d", want, got)
	}
}

func writeTestFile(t *testing.T, path, content string) {
	t.Helper()

	if err := os.WriteFile(path, []byte(content), 0o644); err != nil {
		t.Fatalf("write %s: %v", path, err)
	}
}

func waitForEvents(t *testing.T, events <-chan models.AutomationRunEventV1, timeout time.Duration) []models.AutomationRunEventV1 {
	t.Helper()

	collected := []models.AutomationRunEventV1{}
	deadline := time.After(timeout)
	for {
		select {
		case event := <-events:
			collected = append(collected, event)
			if event.Status != models.JobStatusRunning {
				return collected
			}
		case <-deadline:
			t.Fatalf("timed out waiting for a terminal automation event; got %+v", collected)
		}
	}
}
